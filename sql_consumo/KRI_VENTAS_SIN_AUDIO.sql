FROM DLAB_GEC.M_EXP_VENTAS_PP
WHERE MESDESEMBOLSO IS NOT NULL
UNION ALL
SELECT MESDESEMBOLSO, TIP_CLIENTE, CAST(CAST(FECDESEMB AS FORMAT 'YYYYMMDD') AS VARCHAR(8)), DIA, CODDOC, CODPROMOT AS REG_EJECUTIVO
FROM DLAB_GEC.M_EXP_VENTAS_EC
UNION ALL
SELECT MESDESEMBOLSO, TIP_CLIENTE, CAST(CAST(FECDESEMBOLSO AS FORMAT 'YYYYMMDD') AS VARCHAR(8)), DIA, CODDOC, CODPROMOT AS REG_EJECUTIVO
FROM DLAB_GEC.M_EXP_VENTAS_CD
WHERE COD_CARGA = :periodo
UNION ALL
SELECT MESDESEMBOLSO, TIP_CLIENTE, CAST(CAST(FECDESEMB AS FORMAT 'YYYYMMDD') AS VARCHAR(8)), DIA, CODDOC, CODPROMOT AS REG_EJECUTIVO
FROM DLAB_GEC.M_EXP_VENTAS_CON
UNION ALL
SELECT MESDESEMBOLSO, TIP_CLIENTE, CAST(CAST(FECDESEMBOLSO AS FORMAT 'YYYYMMDD') AS VARCHAR(8)), DIA, CODDOC, CODPROMOT AS REG_EJECUTIVO
FROM DLAB_GEC.M_EXP_VENTAS_UPG
UNION ALL
SELECT MESDESEMBOLSO, TIP_CLIENTE, CAST(CAST(FECDESEMBOLSO AS FORMAT 'YYYYMMDD') AS VARCHAR(8)), DIA, CODDOC, CODPROMOT AS REG_EJECUTIVO
FROM DLAB_GEC.M_EXP_VENTAS_IL;

COLLECT STATISTICS ON DLAB_GEC.M_EXP_CO_KRI_VENTA_TOTAL COLUMN (CODDOC, REG_EJECUTIVO);


-- [PASO 3]: Inicializar TIP_CLIENTE en M_EXP_TRAFICO_GENESYS (Requerido para cruces de DNI)
UPDATE DLAB_GEC.M_EXP_TRAFICO_GENESYS 
FROM DLAB_GEC.M_EXP_TELEVENTAS_EJECUTIVOS B
SET TIP_CLIENTE = B.SUB_EQUIPO
WHERE USERNAME = B.REG_EJECUTIVO;


-- [PASO 3.1]: Actualizar DNI en M_EXP_TRAFICO_GENESYS (Por ANI - Carga Actual y Digital)
UPDATE DLAB_GEC.M_EXP_TRAFICO_GENESYS
FROM (
    SELECT TELEFONO, NUMERO_DOCUMENTO, TIP_CLIENTE
    FROM (
        SELECT TELEFONO, NUMERO_DOCUMENTO, TIP_CLIENTE
        FROM DLAB_GEC.TLV_CARGA_ACTUAL WHERE TELEFONO IS NOT NULL
        UNION ALL
        SELECT TELEFONO, NUMERO_DOCUMENTO, TIP_CLIENTE
        FROM DLAB_GEC.TLV_CARGA_ACTUAL_DIGITAL WHERE TELEFONO IS NOT NULL
    ) U
    QUALIFY ROW_NUMBER() OVER(PARTITION BY TELEFONO, TIP_CLIENTE ORDER BY NUMERO_DOCUMENTO ASC) = 1
) B
SET DNI = B.NUMERO_DOCUMENTO
WHERE DNI IS NULL
  AND ANI = B.TELEFONO
  AND (
      (B.TIP_CLIENTE IN ('C','NC','2DA','DTC') AND DLAB_GEC.M_EXP_TRAFICO_GENESYS.TIP_CLIENTE IN ('DTC','TC')) OR
      (B.TIP_CLIENTE IN ('DPP','PP') AND DLAB_GEC.M_EXP_TRAFICO_GENESYS.TIP_CLIENTE IN ('DPP','PP')) OR
      (B.TIP_CLIENTE IN ('DEC','EC') AND DLAB_GEC.M_EXP_TRAFICO_GENESYS.TIP_CLIENTE IN ('DEC','EC')) OR
      (B.TIP_CLIENTE IN ('DCD','CD') AND DLAB_GEC.M_EXP_TRAFICO_GENESYS.TIP_CLIENTE IN ('DCD','CD')) OR
      (B.TIP_CLIENTE IN ('DCO','CON') AND DLAB_GEC.M_EXP_TRAFICO_GENESYS.TIP_CLIENTE IN ('DCO','CON')) OR
      (B.TIP_CLIENTE IN ('PRT','UPG','IL','TCA','PA','DTCA','DUPG','DIL','DPA','REPRO') AND DLAB_GEC.M_EXP_TRAFICO_GENESYS.TIP_CLIENTE = 'PRT')
  );


