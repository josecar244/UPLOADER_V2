    A.MESDESEMBOLSO, A.TIP_CLIENTE, A.FECDESEMB, A.DIA, A.CODDOC, A.REG_EJECUTIVO, 
    B.NOM_EJECUTIVO, B.NOM_SUPERVISOR, A.MONTO_APROB, A.FLAG_SEG, A.FLAG_CD40K, 
    A.REQUIERE_VAL, A.VALIDACION_CORRECTA, A.VALIDACION_SIN_VAL, A.VALIDACION_FALLIDA, 
    A.TRANSFER_IVR, A.RANGO_TIEMPO, A.FLAG_EVALUADO, NULL AS FLAG_REGISTRO, NULL AS PRT_SEG
