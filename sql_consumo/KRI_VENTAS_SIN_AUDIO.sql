-- ==============================================================================
-- PROCESO: KRI_VENTAS_SIN_AUDIO (Ventas Sin Audio KRI)
-- OPTIMIZACIÓN: 
--   1. Consolidación de ventas del mes mediante UNION ALL (Data Flow VENTAS*).
--   2. Limpieza e inyección en TEMP_TRAFICO con cruces de telefonía inline.
--   3. Unificación de actualizaciones de origen de llamada y marcas de audio.
--   4. Uso de la cláusula nativa QUALIFY y COLLECT STATISTICS.
-- ==============================================================================

-- [PASO 1]: Limpieza de tabla consolidada general
