-- [PASO 4.1]: Cruzar DNI en M_EXP_TRAFICO_GENESYS con Gob Datos (Por ANI - Filtrado selectivo)
UPDATE DLAB_GEC.M_EXP_TRAFICO_GENESYS
FROM (
    SELECT NUMTELEFONO, CODDOC
    FROM E_DW_VIEWS.V_CONT_TELEFONO_APICLIENTE
    WHERE FLG_VALIDADO = 1
      AND NUMTELEFONO IN (
          SELECT ANI FROM DLAB_GEC.M_EXP_TRAFICO_GENESYS 
          WHERE DNI IS NULL AND ANI IS NOT NULL
      )
    QUALIFY ROW_NUMBER() OVER(PARTITION BY NUMTELEFONO ORDER BY CODDOC ASC) = 1
) B
SET DNI = B.CODDOC
WHERE DNI IS NULL
  AND ANI = B.NUMTELEFONO;


-- [PASO 4.2]: Cruzar DNI en M_EXP_TRAFICO_GENESYS con Gob Datos (Por DNIS - Filtrado selectivo)
UPDATE DLAB_GEC.M_EXP_TRAFICO_GENESYS
FROM (
    SELECT NUMTELEFONO, CODDOC
    FROM E_DW_VIEWS.V_CONT_TELEFONO_APICLIENTE
    WHERE FLG_VALIDADO = 1
      AND NUMTELEFONO IN (
          SELECT DNIS FROM DLAB_GEC.M_EXP_TRAFICO_GENESYS 
          WHERE DNI IS NULL AND DNIS IS NOT NULL
      )
    QUALIFY ROW_NUMBER() OVER(PARTITION BY NUMTELEFONO ORDER BY CODDOC ASC) = 1
