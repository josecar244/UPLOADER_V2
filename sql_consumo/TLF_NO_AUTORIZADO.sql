-- ==============================================================================
-- PROCESO: TLF_NO_AUTORIZADO (Teléfonos No Autorizados - COMPLETADO Y OPTIMIZADO)
-- OPTIMIZACIÓN: 
--   1. Reemplazo de drops y creates por DELETE/INSERT para conservar índices y stats.
--   2. Parametrización dinámica de periodos (:periodo, :periodo_num).
--   3. Unificación y estructuración secuencial limpia.
-- ==============================================================================

-- ========================================== 
-- [PROCESANDO PRODUCTO: TC] 
-- ========================================== 
DELETE FROM DLAB_GEC.M_EXP_TLFNO_AUTORIZADO_TC ALL;

INSERT INTO DLAB_GEC.M_EXP_TLFNO_AUTORIZADO_TC (NUM_DOCUMENTO, REG_EJECUTIVO, NUM_TELEFONO, TIEMPO, RANGO_TIEMPO, GD_VAL, CA_VAL, DE_VAL, TIPO_VAL, FB_VAL, GRUPO_ORIGEN, ORIGEN, MONTO_APROB, FECDESEMB, DIA)
SELECT 
NUM_DOCUMENTO, 
REG_EJECUTIVO, 
NUM_TELEFONO, 
TIEMPO_SEG AS TIEMPO,
CAST(NULL AS VARCHAR(20)) AS RANGO_TIEMPO,
CAST(NULL AS INT) AS GD_VAL,
CAST(NULL AS INT) AS CA_VAL,
CAST(NULL AS INT) AS DE_VAL,
CAST(NULL AS VARCHAR(50)) AS TIPO_VAL,
CAST(NULL AS INT) AS FB_VAL,
CAST(NULL AS VARCHAR(15)) AS GRUPO_ORIGEN,
CAST(NULL AS VARCHAR(15)) AS ORIGEN,
CAST(NULL AS INT) AS MONTO_APROB,
CAST(NULL AS VARCHAR(10)) AS FECDESEMB,
CAST(NULL AS INT) AS DIA

FROM (
			SELECT NUM_DOCUMENTO, REG_EJECUTIVO, NUM_TELEFONO, TIEMPO_SEG, ROW_NUMBER() OVER(PARTITION BY NUM_DOCUMENTO, REG_EJECUTIVO ORDER BY TIEMPO_SEG DESC) AS ROWX
			FROM (
			
			SELECT A.NUM_DOCUMENTO, A.REG_EJECUTIVO, A.TELEFONO AS NUM_TELEFONO, SUM(EXTRACT(HOUR FROM A.DURACION_LLAMADA) * 3600
																										 + EXTRACT(MINUTE FROM A.DURACION_LLAMADA) * 60
																										 + EXTRACT(SECOND FROM A.DURACION_LLAMADA)) AS TIEMPO_SEG
			FROM DLAB_GEC.TEMP_TRAFICO A, DLAB_GEC.M_EXP_VENTAS_TC B
			WHERE A.NUM_DOCUMENTO = B.CODDOC
			AND A.REG_EJECUTIVO = B.CODPROMOT
			GROUP BY A.NUM_DOCUMENTO, A.REG_EJECUTIVO, A.TELEFONO
			
			UNION ALL 
			
			--- TABLA GENESYS 
			SELECT DISTINCT DNI AS NUM_DOCUMENTO, username AS REG_EJECUTIVO, ANI AS NUM_TELEFONO,
			SUM(((EXTRACT(  HOUR FROM sessionendtime) - EXTRACT(HOUR FROM sessionstarttime))) * 3600
			      + ((EXTRACT(MINUTE FROM sessionendtime) - EXTRACT(MINUTE FROM sessionstarttime)) * 60)
			      + ((EXTRACT(SECOND FROM sessionendtime) - EXTRACT(SECOND FROM sessionstarttime)))) AS TIEMPO_SEG 
			      FROM DLAB_GEC.M_EXP_TRAFICO_GENESYS A, DLAB_GEC.M_EXP_VENTAS_TC B
			WHERE NUM_TELEFONO IS NOT NULL 
			AND A.DNI = B.CODDOC
			AND A.USERNAME = B.CODPROMOT
			GROUP BY DNI, USERNAME, ANI
			
			UNION ALL
			
			SELECT DISTINCT DNI AS NUM_DOCUMENTO, username AS REG_EJECUTIVO, DNIS AS NUM_TELEFONO,
			SUM(((EXTRACT(  HOUR FROM sessionendtime) - EXTRACT(HOUR FROM sessionstarttime))) * 3600
			      + ((EXTRACT(MINUTE FROM sessionendtime) - EXTRACT(MINUTE FROM sessionstarttime)) * 60)
			      + ((EXTRACT(SECOND FROM sessionendtime) - EXTRACT(SECOND FROM sessionstarttime)))) AS TIEMPO_SEG 
			      FROM DLAB_GEC.M_EXP_TRAFICO_GENESYS A, DLAB_GEC.M_EXP_VENTAS_TC B
			WHERE NUM_TELEFONO IS NOT NULL
			AND A.DNI = B.CODDOC
			AND A.USERNAME = B.CODPROMOT
			GROUP BY DNI, USERNAME, DNIS
			
			UNION ALL 
			
			--- TABLA DERIVABT 
			
			SELECT DISTINCT DNI AS NUM_DOCUMENTO, REG_EJECUTIVO, TELF_ANI AS NUM_TELEFONO,
			SUM(((EXTRACT(  HOUR FROM sessionendtime) - EXTRACT(HOUR FROM sessionstarttime))) * 3600
			      + ((EXTRACT(MINUTE FROM sessionendtime) - EXTRACT(MINUTE FROM sessionstarttime)) * 60)
			      + ((EXTRACT(SECOND FROM sessionendtime) - EXTRACT(SECOND FROM sessionstarttime)))) AS TIEMPO_SEG 
			      FROM DLAB_GEC.M_EXP_DERIVA_BT_TIEMPOS A, DLAB_GEC.M_EXP_VENTAS_TC B
			WHERE A.DNI = B.CODDOC
			AND A.REG_EJECUTIVO = B.CODPROMOT
			AND NUM_TELEFONO IS NOT NULL
			AND NUM_TELEFONO NOT IN ('localhost')
			AND NUM_TELEFONO NOT LIKE ('%.%')
			GROUP BY DNI, REG_EJECUTIVO, TELF_ANI
			
			
			UNION ALL 
			
			SELECT DISTINCT DNI AS NUM_DOCUMENTO, REG_EJECUTIVO, TELF_DNIS AS NUM_TELEFONO,
			SUM(((EXTRACT(  HOUR FROM sessionendtime) - EXTRACT(HOUR FROM sessionstarttime))) * 3600
			      + ((EXTRACT(MINUTE FROM sessionendtime) - EXTRACT(MINUTE FROM sessionstarttime)) * 60)
			      + ((EXTRACT(SECOND FROM sessionendtime) - EXTRACT(SECOND FROM sessionstarttime)))) AS TIEMPO_SEG 
			      FROM DLAB_GEC.M_EXP_DERIVA_BT_TIEMPOS A, DLAB_GEC.M_EXP_VENTAS_TC B
			WHERE A.DNI = B.CODDOC
			AND A.REG_EJECUTIVO = B.CODPROMOT
			AND NUM_TELEFONO IS NOT NULL
			AND NUM_DOCUMENTO IS NOT NULL
			AND NUM_TELEFONO NOT IN ('localhost')
			AND NUM_TELEFONO NOT LIKE ('%.%')
			AND NUM_TELEFONO NOT LIKE ('%11311%')
			AND REG_EJECUTIVO NOT LIKE ('%TLV_%')
			GROUP BY DNI, REG_EJECUTIVO, TELF_DNIS
			
			) X
  ) Z
  WHERE ROWX = 1
  AND NUM_DOCUMENTO IS NOT NULL;

