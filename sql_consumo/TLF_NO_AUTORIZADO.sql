FROM (
    SELECT NUMERO_DOCUMENTO, TELEFONO
    FROM (
        SELECT NUMERO_DOCUMENTO, TELEFONO,
               ROW_NUMBER() OVER (PARTITION BY NUMERO_DOCUMENTO, TELEFONO ORDER BY 1) AS RN
        FROM DLAB_GEC.TLV_CARGA_ACTUAL
        WHERE TIP_CLIENTE IN ('NC','C','2DA')
    ) AS SUB
    WHERE RN = 1
