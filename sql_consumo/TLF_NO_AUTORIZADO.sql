SET CA_VAL = 1,
    TIPO_VAL = 'CARGA ACTUAL'
WHERE DLAB_GEC.M_EXP_TLFNO_AUTORIZADO_TC.NUM_DOCUMENTO = B.NUMERO_DOCUMENTO
  AND DLAB_GEC.M_EXP_TLFNO_AUTORIZADO_TC.NUM_TELEFONO = B.TELEFONO
