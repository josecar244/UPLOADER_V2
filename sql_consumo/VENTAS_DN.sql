    SUBEQUIPO, FECDESEMBOLSO, DIA, CODDOC, MONTO_APROB, FECINGRESO
)
SELECT 
    A.PERIODO_VAL AS MESDESEMBOLSO,
    'PA' AS TIP_CLIENTE,
    'TLV' AS GESTION, 
    A.PROMOTOR_CD AS CODPROMOT, 
    B.NOM_EJECUTIVO AS NOMPROMOT,
    B.NOM_SUPERVISOR AS NOMSUPER,
    'GESTION PORTAFOLIO' AS EQUIPO, 
    'LEALTAD' AS SUBEQUIPO,
    SUBSTRING(A.SOLICITUD_FC FROM 1 FOR 4) || SUBSTRING(A.SOLICITUD_FC FROM 6 FOR 2) || SUBSTRING(A.SOLICITUD_FC FROM 9 FOR 2) AS FECDESEMBOLSO,
    SUBSTRING(A.SOLICITUD_FC FROM 9 FOR 2) AS DIA,
    A.DOCUMENTO_NUM AS CODDOC,
    0 AS MONTO_APROB,
    A.SOLICITUD_FC AS FECINGRESO
