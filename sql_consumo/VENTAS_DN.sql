-- DTC: Tarjetas de Crédito
DELETE FROM DLAB_GEC.M_EXP_VENTAS_TC ALL;

INSERT INTO DLAB_GEC.M_EXP_VENTAS_TC (
    MESDESEMBOLSO, TIP_CLIENTE, GESTION, CODPROMOT, NOMPROMOT, NOMSUPER, EQUIPO, 
    SUB_EQUIPO, FECDESEMB, DIA, CODDOC, MONTO_APROB, ESTADO, TIPOAPROB, DISPOEFECT, 
    ESTACIVIL, SITLABORAL, CORREO, TELCELUL, ECREGIST, FECENTREGA, FECACTIVA, 
    NOMCLIENTE, TARJETA_NUM, FLAGSEGURO
)
SELECT 
    A.PERIODO_VAL AS MESDESEMBOLSO,
    'DTC' AS TIP_CLIENTE,
    'TLV' AS GESTION,
    A.PROMOTOR_CD AS CODPROMOT,
    A.PROMOTOR_NM AS NOMPROMOT,
    A.SUPERVISOR_NM AS NOMSUPER,
    A.EquipoVenta_Dsc AS EQUIPO,
    A.SubEquipoVenta_Dsc AS SUB_EQUIPO,
    A.AprobacionExpedADQ_Fc AS FECDESEMB,
    EXTRACT(DAY FROM AprobacionExpedADQ_Fc) AS DIA,
    TRIM(A.DOCUMENTO_NUM) AS CODDOC,
    A.LineaTc_Amt AS MONTO_APROB,
    A.EstadoSolicitud_Dsc AS ESTADO, 
    A.TipoTcAprobada_Dsc AS TIPOAPROB, 
    A.DisposicionEfectivo_Amt AS DISPOEFECT, 
    A.EstadoCivilCli_Dsc AS ESTACIVIL, 
    A.SituacionLaboralCli_Dsc AS SITLABORAL,
    A.CorreoCli_Dsc AS CORREO,		
    A.TelefonoCelular_Num AS TELCELUL,
    A.IngresoExpedADQ_Fc AS ECREGIST,
    A.EntregaTc_Fc AS FECENTREGA, 
    A.ActivaTc_Fc AS FECACTIVA, 
    A.Cliente_Nm AS NOMCLIENTE,
    A.TARJETA_NUM,
    CASE WHEN seg.DNI_TITULAR IS NOT NULL THEN 1 ELSE NULL END AS FLAGSEGURO
FROM E_DW_VIEWS.V_FCT_RT_TC_HISTORICO A
LEFT JOIN (
    SELECT DISTINCT DNI_TITULAR, CODPROMOT 
    FROM E_DW_VIEWS_DLAB.V_DLAB_CGR_SEGUROS_VENTAS 
    WHERE MESVENTA = :periodo
      AND PRODUCTO = 'IBK - SEGURO PROTECCION DE TARJETAS 360'
) seg
  ON TRIM(A.DOCUMENTO_NUM) = TRIM(seg.DNI_TITULAR)
 AND A.PROMOTOR_CD = seg.CODPROMOT
WHERE A.mesingresoexpedADQ_DSC = :periodo
  AND A.PROMOTOR_CD IN (SELECT REG_EJECUTIVO FROM DLAB_GEC.M_EXP_TELEVENTAS_EJECUTIVOS WHERE SUB_EQUIPO='TC')
  AND A.EquipoVenta_Dsc IN ('TLV TARJETAS','Televentas')
  AND A.ESTADOSOLICITUD_DSC = 'Aprobado'
  AND A.TIPOTRAMITE_DSC <> 'MIGRACIÓN TC'
  AND A.OPERACION_CD IN (1,2)
  AND A.ESTADOSOLICITUD_CD IN (3);

COLLECT STATISTICS ON DLAB_GEC.M_EXP_VENTAS_TC COLUMN (CODDOC, CODPROMOT);


