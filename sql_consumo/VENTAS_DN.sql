  ON A.PROMOTOR_CD = B.REG_EJECUTIVO
WHERE A.PERIODO_VAL = :periodo_prev
  AND A.SOLICITUD_PERIODO_VAL = :periodo
  AND A.ESTADO_CD = 'A'
  AND A.RUBRO_CD <> '22'
  AND A.PROMOTOR_CD IN (SELECT REG_EJECUTIVO FROM DLAB_GEC.M_EXP_TELEVENTAS_EJECUTIVOS WHERE SUB_EQUIPO = 'PRT');

COLLECT STATISTICS ON DLAB_GEC.M_EXP_VENTAS_PA COLUMN (CODDOC);


-- SEG: Seguros
DELETE FROM DLAB_GEC.M_EXP_VENTAS_SEG ALL;

INSERT INTO DLAB_GEC.M_EXP_VENTAS_SEG (
    MESDESEMBOLSO, TIP_CLIENTE, GESTION, CODPROMOT, NOMPROMOT, NOMSUPER, EQUIPO, 
    SUBEQUIPO, FECDESEMBOLSO, DIA, CODDOC, MONTO_APROB, FECINGRESO
)
SELECT 
    A.MESVENTA AS MESDESEMBOLSO,
    'SEG' AS TIP_CLIENTE,
    CASE A.PRODUCTO 
        WHEN 'IBK - SEGURO PROTECCION DE TARJETAS 360' THEN 'STC'
        WHEN 'Vive Salud' THEN 'SVS'
        WHEN 'IBK - PROGRAMA ONCOLÓGICO' THEN 'SPO'
        ELSE '' 
    END AS GESTION,
    A.CODPROMOT,
    B.NOM_EJECUTIVO AS NOMPROMOT,
    B.NOM_SUPERVISOR AS NOMSUPER,
    'GESTION PORTAFOLIO' AS EQUIPO,
    'LEALTAD' AS SUBEQUIPO,
    SUBSTRING(A.FECVENTA FROM 7 FOR 4) || SUBSTRING(A.FECVENTA FROM 4 FOR 2) || SUBSTRING(A.FECVENTA FROM 1 FOR 2) AS FECDESEMBOLSO,
    SUBSTRING(A.FECVENTA FROM 1 FOR 2) AS DIA,
    A.DNI_TITULAR AS CODDOC,
    0 AS MONTO_APROB,
    A.FECVENTA AS FECINGRESO
FROM E_DW_VIEWS_DLAB.V_DLAB_CGR_SEGUROS_VENTAS A
LEFT JOIN DLAB_GEC.M_EXP_TELEVENTAS_EJECUTIVOS B
  ON A.CODPROMOT = B.REG_EJECUTIVO
WHERE A.MESVENTA = :periodo
  AND A.CODPROMOT IN (SELECT REG_EJECUTIVO FROM DLAB_GEC.M_EXP_TELEVENTAS_EJECUTIVOS WHERE SUB_EQUIPO = 'SEG');

COLLECT STATISTICS ON DLAB_GEC.M_EXP_VENTAS_SEG COLUMN (CODDOC);
