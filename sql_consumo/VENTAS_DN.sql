-- DCD: Compra de Deuda
DELETE FROM DLAB_GEC.M_EXP_VENTAS_CD ALL;

INSERT INTO DLAB_GEC.M_EXP_VENTAS_CD (
    MESDESEMBOLSO, TIP_CLIENTE, GESTION, CODPROMOT, NOMPROMOT, NOMSUPER, EQUIPO, 
    SUBEQUIPO, FECDESEMBOLSO, DIA, CODDOC, MONTO_APROB, TASA_MENSUAL, CANT_CUOTAS, 
    TIPO_CD, COD_SOLICITUD, NUM_TARJETA, FLAG_CD40, COD_CARGA
)
SELECT 
    A.MESDESEMBOLSO, 
    'DCD' AS TIP_CLIENTE,
    'TLV' AS GESTION,
    A.CODPROMOT,
    A.NOMPROMOT,
    A.NOMSUPER,
    'TLV PRODUCTOS' AS EQUIPO, 
    'COMPRA DE DEUDA' AS SUBEQUIPO,
    A.FECHA_DESEMBOLSO AS FECDESEMBOLSO,
    EXTRACT(DAY FROM A.FECHA_DESEMBOLSO) AS DIA,
    A.CODDOC,
    A.ADQ_MONTOCDSOL AS MONTO_APROB,
    A.TASA_MENSUAL,
    A.CANT_CUOTAS,
    A.TIPO_CD,
    RIGHT(A.ADQ_NROSOL, 8) AS COD_SOLICITUD, 
    A.NUME_TARJETA AS NUM_TARJETA,
    CASE WHEN b_cd40.NE_COD_EXPE IS NOT NULL THEN 'SI' ELSE 'NO' END AS FLAG_CD40,
    b_carga.CA_ANIOMES_CARGA AS COD_CARGA
FROM E_DW_VIEWS_DLAB.V_CD_DESEMB_HISTORICO A
LEFT JOIN (
    SELECT DISTINCT NE_COD_EXPE 
    FROM E_DW_VIEWS.V_RSK_ADQ_BTCH_COMPRA_DEUDA
    WHERE NE_COD_EXPE IN (SELECT RIGHT(ADQ_NROSOL, 8) FROM E_DW_VIEWS_DLAB.V_CD_DESEMB_HISTORICO WHERE MESDESEMBOLSO = :periodo_num)
      AND ND_MONTO > 40000
) b_cd40
  ON RIGHT(A.ADQ_NROSOL, 8) = b_cd40.NE_COD_EXPE
LEFT JOIN (
    SELECT NE_COD_EXPE, CA_ANIOMES_CARGA
    FROM E_DW_VIEWS.V_RSK_ADQ_BTCH_COMPRA_DEUDA
    WHERE NE_COD_EXPE IN (SELECT RIGHT(ADQ_NROSOL, 8) FROM E_DW_VIEWS_DLAB.V_CD_DESEMB_HISTORICO WHERE MESDESEMBOLSO = :periodo_num)
    QUALIFY ROW_NUMBER() OVER(PARTITION BY NE_COD_EXPE ORDER BY CA_ANIOMES_CARGA ASC) = 1
) b_carga
  ON RIGHT(A.ADQ_NROSOL, 8) = b_carga.NE_COD_EXPE
WHERE A.MESDESEMBOLSO = :periodo_num
  AND A.CODPROMOT IN (SELECT REG_EJECUTIVO FROM DLAB_GEC.M_EXP_TELEVENTAS_EJECUTIVOS WHERE SUB_EQUIPO ='CD')
  AND A.TIPONOCOMISION IS NULL
  AND A.FLAG_VALIDO = 'S'
  AND A.IMPOR_INIC_DESEMBOLSO IS NOT NULL;

COLLECT STATISTICS ON DLAB_GEC.M_EXP_VENTAS_CD COLUMN (CODDOC, COD_SOLICITUD);


