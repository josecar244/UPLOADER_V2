-- -------------------------------------------------------------
-- PASO 1: Creación de la Tabla Consolidada
-- -------------------------------------------------------------
-- Nota: Si la tabla ya existe, se puede omitir o limpiar.
-- DROP TABLE DLAB_GEC.REPORTE_RETENCION_CONVENIOS;

CREATE MULTISET TABLE DLAB_GEC.REPORTE_RETENCION_CONVENIOS ,FALLBACK ,
     NO BEFORE JOURNAL,
     NO AFTER JOURNAL,
     CHECKSUM = DEFAULT,
     DEFAULT MERGEBLOCKRATIO,
     MAP = TD_MAP1
     (
      RET_CONVENIOS_COBRANZAS INTEGER,
      RET_CONVENIOS_COMPRA_DE_DEUDA INTEGER,
      RET_CONVENIOS_CONSULTAS_GENERALES INTEGER,
      RET_CONVENIOS_DEVOLUCION_CUOTAS INTEGER,
      RET_CONVENIOS_INFO_CAMPANAS INTEGER,
      RET_CONVENIOS_MAYOR_IMPORTE INTEGER,
      RET_CONVENIOS_MEDIOS_PROPIOS INTEGER,
      RET_CONVENIOS_OFF_MAVERICK INTEGER,
      RET_CONVENIOS_PEDIDOS_RECLAMOS INTEGER,
      RET_CONVENIOS_RET_AMPLIACION INTEGER,
      RET_CONVENIOS_RET_BAJA_TASA INTEGER,
      RET_CONVENIOS_SOL_CANCELACION INTEGER,
      RET_CONVENIOS_SOL_CRONOGRAMA INTEGER,
      RET_CONVENIOS_SOL_DEUDA_TOTAL INTEGER,
      RET_CONVENIOS_SOL_TASA_INTERES INTEGER,
      RET_CONVENIOS_TASA_INTERES INTEGER,
      TiempoLlamada INTEGER,
      TIEMPO_SILENCIO INTEGER,
      DniCliente VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      RegistroAgente VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      FechaLlamada TIMESTAMP(6),
      NUM_TELEF VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      DNIS VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      Attemps INTEGER,
      conID VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      Tipificacion VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      IDContacto VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      cti_BT_Segmento VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      Area VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      Periodo VARCHAR(6) CHARACTER SET LATIN NOT CASESPECIFIC,
      TIEMPO_SILENCIO_HH_MM_SS FLOAT,
      TIEMPO_LLAMADA_HH_MM_SS FLOAT,
      TIEMPO_HABLADO_HH_MM_SS FLOAT,
      Direccion VARCHAR(15) CHARACTER SET UNICODE NOT CASESPECIFIC,
      Empleado VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      SEGMENTO VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      FAMILIA VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      MOTIVO VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      RESPUESTA VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      GESTION VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      PLAZA VARCHAR(255) CHARACTER SET UNICODE NOT CASESPECIFIC,
      AC_TASA INTEGER,
      AC_AMPLIACION INTEGER,
      TOTAL_RETENCIONES INTEGER,
      CLIENTE_GESTIONABLE INTEGER,
      CANCELACIONES_EFECTIVAS INTEGER,
      RETENCION_TASA INTEGER,
      RETENCION_MONTO INTEGER,
      ACEP_MAVERINK INTEGER,
      POTENCIAL_MAVERINK INTEGER,
      RANGO_LLAMADA VARCHAR(50) CHARACTER SET UNICODE NOT CASESPECIFIC,
      TiempoLlamada_retenciones FLOAT,
      Tiemposilencio_retenciones FLOAT,
      Tiempohablado_retenciones FLOAT,
      TOTAL_MOTIVOS_ANULACION INTEGER,
      TiempoLlamada_ofrecimiento FLOAT,
      Tiemposilencio_ofrecimiento FLOAT,
      Tiempohablado_ofrecimiento FLOAT,
      TiempoLlamada_POST_VENTA FLOAT,
      Tiemposilencio_POST_VENTA FLOAT,
      Tiempohablado_POST_VENTA FLOAT,
      TiempoLlamada_cancelaciones FLOAT,
      Tiemposilencio_cancelaciones FLOAT,
      Tiempohablado_cancelaciones FLOAT,
      TiempoLlamada_Cross FLOAT,
      Tiemposilencio_Cross FLOAT,
      Tiempohablado_Cross FLOAT,
      ALERTAS_RETENCIONES VARCHAR(100) CHARACTER SET UNICODE NOT CASESPECIFIC
     )
PRIMARY INDEX ( conID );


-- -------------------------------------------------------------
-- PASO 2: Creación de la Vista para Reportes (Power BI / Visualización)
-- -------------------------------------------------------------
-- Mapea los nombres técnicos de columnas en Teradata a los nombres originales
-- con espacios, acentos y mayúsculas que espera el reporte original.
-- REPLACE VIEW se auto-reemplaza si la vista ya existe.

REPLACE VIEW DLAB_GEC.VISTA_REPORTE_RETENCIONES_CONVENIOS AS (
SELECT 
    1 AS CANT_TRANSCRIPCIONES,
    RET_CONVENIOS_COBRANZAS AS "RET_CONVENIOS - COBRANZAS",
    RET_CONVENIOS_COMPRA_DE_DEUDA AS "RET_CONVENIOS - COMPRA DE DEUDA",
    RET_CONVENIOS_CONSULTAS_GENERALES AS "RET_CONVENIOS - CONSULTAS GENERALES",
    RET_CONVENIOS_DEVOLUCION_CUOTAS AS "RET_CONVENIOS - DEVOLUCIÓN DE CUOTAS",
    RET_CONVENIOS_INFO_CAMPANAS AS "RET_CONVENIOS - INFORMACION DE CAMPAÑAS",
    RET_CONVENIOS_MAYOR_IMPORTE AS "RET_CONVENIOS - MAYOR IMPORTE",
    RET_CONVENIOS_MEDIOS_PROPIOS AS "RET_CONVENIOS - MEDIOS PROPIOS",
    RET_CONVENIOS_OFF_MAVERICK AS "RET_CONVENIOS - OFF MAVERICK",
    RET_CONVENIOS_PEDIDOS_RECLAMOS AS "RET_CONVENIOS - PEDIDOS Y RECLAMOS",
    RET_CONVENIOS_RET_AMPLIACION AS "RET_CONVENIOS - RETENCIONES POR AMPLIACIÓN",
    RET_CONVENIOS_RET_BAJA_TASA AS "RET_CONVENIOS - RETENCIONES POR BAJA DE TASA",
    RET_CONVENIOS_SOL_CANCELACION AS "RET_CONVENIOS - SOLICITUD DE CANCELACION",
    RET_CONVENIOS_SOL_CRONOGRAMA AS "RET_CONVENIOS - SOLICITUD DE CRONOGRAMA DE PAGOS",
    RET_CONVENIOS_SOL_DEUDA_TOTAL AS "RET_CONVENIOS - SOLICITUD DE DEUDA TOTAL",
    RET_CONVENIOS_SOL_TASA_INTERES AS "RET_CONVENIOS - SOLICITUD DE TASA DE INTERES",
    RET_CONVENIOS_TASA_INTERES AS "RET_CONVENIOS - TASA DE INTERES",
    CASE WHEN (RET_CONVENIOS_OFF_MAVERICK = 1 AND Direccion = 'Saliente') THEN 1 ELSE 0 END AS "RET_CONVENIOS - RET MAVERICK",
    CASE WHEN (RET_CONVENIOS_SOL_CANCELACION = 1 OR RET_CONVENIOS_SOL_CRONOGRAMA = 1 OR RET_CONVENIOS_SOL_DEUDA_TOTAL = 1 OR RET_CONVENIOS_SOL_TASA_INTERES = 1 OR (RET_CONVENIOS_OFF_MAVERICK = 1 AND Direccion = 'Saliente')) THEN 1 ELSE 0 END AS "ALERTAS RETENCIÓN",
    (RET_CONVENIOS_SOL_CANCELACION + RET_CONVENIOS_SOL_CRONOGRAMA + RET_CONVENIOS_SOL_DEUDA_TOTAL + RET_CONVENIOS_SOL_TASA_INTERES + RET_CONVENIOS_OFF_MAVERICK) AS "CANT MOTIVOS ALERTAS RETENCIÓN",
    CASE WHEN (RET_CONVENIOS_RET_AMPLIACION = 1 OR RET_CONVENIOS_RET_BAJA_TASA = 1) THEN 1 ELSE 0 END AS "TOTAL OFRECIMIENTO",
    (RET_CONVENIOS_RET_AMPLIACION + RET_CONVENIOS_RET_BAJA_TASA) AS "CANTIDAD OFRECIMIENTO",
    CASE WHEN (RET_CONVENIOS_COMPRA_DE_DEUDA = 1 OR RET_CONVENIOS_TASA_INTERES = 1 OR RET_CONVENIOS_MAYOR_IMPORTE = 1 OR RET_CONVENIOS_MEDIOS_PROPIOS = 1) THEN 1 ELSE 0 END AS "MOTIVOS_ANULACIÓN",
    TOTAL_MOTIVOS_ANULACION AS "TOTAL_MOTIVOS_ANULACIÓN",
    CASE WHEN (RET_CONVENIOS_INFO_CAMPANAS = 1 OR RET_CONVENIOS_CONSULTAS_GENERALES = 1 OR RET_CONVENIOS_DEVOLUCION_CUOTAS = 1 OR RET_CONVENIOS_COBRANZAS = 1 OR RET_CONVENIOS_PEDIDOS_RECLAMOS = 1) THEN 1 ELSE 0 END AS "TOTAL_POST_VENTA",
    AC_TASA,
    AC_AMPLIACION AS "AC_AMPLIACIÓN",
    Periodo,
    TiempoLlamada,
    DniCliente,
    RegistroAgente,
    FechaLlamada,
    TO_CHAR(FechaLlamada, 'YYYY-MM-DD HH24:MI:SS') AS FECHA,
    NUM_TELEF,
    DNIS,
    Attemps,
    conID,
    Tipificacion AS "Tipificación",
    IDContacto,
    cti_BT_Segmento,
    Direccion AS "Dirección",
    TIEMPO_SILENCIO,
    RANGO_LLAMADA,
    TIEMPO_SILENCIO_HH_MM_SS AS "TIEMPO_SILENCIO_HH:MM:SS",
    TIEMPO_LLAMADA_HH_MM_SS AS "TIEMPO_LLAMADA_HH:MM:SS",
    TIEMPO_HABLADO_HH_MM_SS AS "TIEMPO_HABLADO_HH:MM:SS",
    SEGMENTO,
    FAMILIA,
    MOTIVO,
    RESPUESTA,
    GESTION,
    EXTRACT(DAY FROM FechaLlamada) AS DIA,
    Empleado,
    TiempoLlamada_retenciones,
    Tiemposilencio_retenciones,
    Tiempohablado_retenciones,
    TOTAL_RETENCIONES,
    TiempoLlamada_ofrecimiento,
    Tiemposilencio_ofrecimiento,
    Tiempohablado_ofrecimiento,
    TiempoLlamada_POST_VENTA,
    Tiemposilencio_POST_VENTA,
    Tiempohablado_POST_VENTA,
    TiempoLlamada_cancelaciones,
    Tiemposilencio_cancelaciones,
    Tiempohablado_cancelaciones,
    TiempoLlamada_Cross,
    Tiemposilencio_Cross,
    Tiempohablado_Cross,
    POTENCIAL_MAVERINK,
    ALERTAS_RETENCIONES,
    CLIENTE_GESTIONABLE,
    CANCELACIONES_EFECTIVAS,
    RETENCION_TASA,
    RETENCION_MONTO,
    ACEP_MAVERINK,
    PLAZA
FROM DLAB_GEC.REPORTE_RETENCION_CONVENIOS
);
