-- PASO 3: DEDUPLICACIÓN DE FUENTES LPDP (Tablas Volátiles)
-- -------------------------------------------------------------

CREATE VOLATILE TABLE VT_LPDP_CARGA_ACTUAL AS (
    SELECT NUMERO_DOCUMENTO, TIP_CLIENTE, VARIABLE_26
    FROM (
        SELECT NUMERO_DOCUMENTO, TIP_CLIENTE, VARIABLE_26,
               ROW_NUMBER() OVER (PARTITION BY NUMERO_DOCUMENTO, TIP_CLIENTE ORDER BY NUMERO_DOCUMENTO ASC) AS rn
        FROM DLAB_GEC.TLV_CARGA_ACTUAL
        WHERE (
            (TIP_CLIENTE IN ('C', 'NC', '2DA', 'PP', 'CON') AND VARIABLE_4 IS NULL)
            OR (TIP_CLIENTE IN ('EC', 'BPE') AND VARIABLE_3 IS NULL AND VARIABLE_4 IS NULL)
        )
    ) AS t
    WHERE rn = 1
) WITH DATA PRIMARY INDEX (NUMERO_DOCUMENTO) ON COMMIT PRESERVE ROWS;

CREATE VOLATILE TABLE VT_LPDP_CARGA_ACTUAL_DIGITAL AS (
    SELECT NUMERO_DOCUMENTO, TIP_CLIENTE, VARIABLE_26
    FROM (
        SELECT NUMERO_DOCUMENTO, TIP_CLIENTE, VARIABLE_26,
               ROW_NUMBER() OVER (PARTITION BY NUMERO_DOCUMENTO, TIP_CLIENTE ORDER BY NUMERO_DOCUMENTO ASC) AS rn
        FROM DLAB_GEC.TLV_CARGA_ACTUAL_DIGITAL
        WHERE TIP_CLIENTE IN ('DTC', 'DPP', 'DEC', 'DCO')
          AND VARIABLE_3 IS NULL
          AND VARIABLE_4 IS NULL
    ) AS t
    WHERE rn = 1
) WITH DATA PRIMARY INDEX (NUMERO_DOCUMENTO) ON COMMIT PRESERVE ROWS;


