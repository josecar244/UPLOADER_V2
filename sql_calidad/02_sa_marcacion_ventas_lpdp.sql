-- 02_SA_MARCACION_VENTAS_LPDP.SQL
-- Script SQL refactorizado aplicando las mejores prácticas de rendimiento en Teradata:
-- 1. Sin sentencias UPDATE secuenciales.
-- 2. Uso intensivo de tablas volátiles (en Spool Space, sin consumir Perm Space).
-- 3. Deduplicación de registros usando ROW_NUMBER() OVER en sentencias SELECT.
-- 4. Sentencias JOIN y CASE WHEN unificadas para el marcado de ventas y LPDP.
-- 5. Carga final usando DELETE ALL e INSERT.
