-- -------------------------------------------------------------
-- PASO 1: LIMPIEZA DE NÚMEROS TELEFÓNICOS (Tabla Volátil VT_SA_CLEANED)
-- -------------------------------------------------------------
CREATE VOLATILE TABLE VT_SA_CLEANED AS (
    SELECT
        s.*,
        TRIM(BOTH ' ' FROM SUBSTR(CASE WHEN CHARACTER_LENGTH(s.TELEF_IN) > 19 THEN s.TELEF_OUT ELSE s.TELEF_IN END, 8)) AS TELEF_IN_CLEANED
    FROM DLAB_GEC.M_EXP_CALIDAD_DATA_SPEECH_ANALYTICS s
) WITH DATA PRIMARY INDEX (CONID) ON COMMIT PRESERVE ROWS;


