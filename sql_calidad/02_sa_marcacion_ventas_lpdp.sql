-- Deduplicación de TC (Período 1 y 2)
CREATE VOLATILE TABLE VT_TC_DEDUP AS (
    SELECT CODDOC, CODPROMOT, DIA,
           CASE WHEN DIA BETWEEN {corte_dia_inicio_1} AND {corte_dia_fin_1} THEN 1 ELSE 2 END AS PeriodType
    FROM (
        SELECT CODDOC, CODPROMOT, DIA,
               ROW_NUMBER() OVER (PARTITION BY CODDOC, (CASE WHEN DIA BETWEEN {corte_dia_inicio_1} AND {corte_dia_fin_1} THEN 1 ELSE 2 END) ORDER BY CODDOC ASC) AS rn
        FROM DLAB_GEC.M_EXP_VENTAS_TC
        WHERE DIA BETWEEN {corte_dia_inicio_1} AND {corte_dia_fin_2}
    ) AS t
    WHERE rn = 1
) WITH DATA PRIMARY INDEX (CODDOC) ON COMMIT PRESERVE ROWS;

